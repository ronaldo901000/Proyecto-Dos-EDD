    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tablaSucursales.getModel();
        
        modelo.setRowCount(0); 
        
        for (int i = 0; i < controlador.getSucursales().getTamaño(); i++) {
            try {
                Sucursal sucursal = controlador.getSucursales().obtenerValor(i);

                modelo.addRow(new Object[]{
                    i,
                    sucursal.getId(),
                    sucursal.getNombre(),
                    sucursal.getUbicacion(),
                    sucursal.getTiempoIngreso(),
                    sucursal.getTiempoTraspaso(),
                    sucursal.getIntervaloDespacho()
                });
            } catch (ListaException ex) {
                JOptionPane.showMessageDialog(this, "Error al cargar datos: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }

        }
    }

